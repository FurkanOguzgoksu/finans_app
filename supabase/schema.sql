-- Supabase panelinde SQL Editor'e yapıştırıp çalıştırın.
-- Betik tekrar çalıştırılabilir: yeni projede tabloları oluşturur, mevcut
-- projede eksik ayarları tamamlar. Mevcut kayıtları silmez.
--
-- Not: Uygulama tarihleri saat dilimi eki olmadan (cihazdaki yerel saat
-- olarak) gönderir; Postgres bunları UTC kabul eder ve uygulama aynı saat
-- değerini geri okur. Paneldeki saatlerin yerel saatle aynı görünmesi bu
-- yüzdendir, saat farkı yoktur.
-- ════════════════════════════════════════════════════════════════════

begin;

-- ─── 1. Tablolar (yeni kurulum) ─────────────────────────────────────

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null,
  type text not null check (type in ('gelir', 'gider')),
  icon text not null default 'category',
  color text not null default '#4CAF50'
);

create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  title text not null,
  amount numeric(14, 2) not null,
  type text not null check (type in ('gelir', 'gider')),
  category_id bigint not null references public.categories (id),
  date timestamptz not null,
  description text,
  receipt_id text,  -- Fiş fotoğrafının/PDF'in cihazdaki dosya yolu
  items_json text,  -- Fiş kalemleri (JSON metni)
  created_at timestamptz not null default now()
);

-- ─── 2. Mevcut tabloların düzeltilmesi ──────────────────────────────

-- Tutar: 'real' tipi yaklaşık 7 hane hassasiyetlidir ve kuruşları
-- kaybeder (1.234.567,89 → 1.234.567,88). Para için 'numeric' kullanılır.
-- Dönüşüm double precision üzerinden yapılır: real doğrudan numeric'e
-- çevrilirse yalnızca 6 hane korunur (1.234.567,88 → 1.234.570,00).
do $$
begin
  if (select data_type from information_schema.columns
      where table_schema = 'public' and table_name = 'transactions'
        and column_name = 'amount') <> 'numeric' then
    alter table public.transactions
      alter column amount type numeric(14, 2)
      using round(amount::double precision::numeric, 2);
  end if;
end $$;

-- Oluşturulma zamanı gönderilmezse sunucu saati yazılır
alter table public.transactions alter column created_at set default now();

-- user_id: kayıt eklenirken oturumdaki kullanıcı otomatik yazılır
alter table public.categories alter column user_id set default auth.uid();
alter table public.transactions alter column user_id set default auth.uid();

-- user_id boş kayıt yoksa kolon zorunlu yapılır. Boş kayıtlar hiçbir
-- kullanıcıya görünmez; varsa silinmez, yalnızca uyarı verilir.
do $$
declare
  t text;
  empty_count bigint;
begin
  foreach t in array array['categories', 'transactions'] loop
    if exists (select 1 from information_schema.columns
               where table_schema = 'public' and table_name = t
                 and column_name = 'user_id' and is_nullable = 'YES') then
      execute format('select count(*) from public.%I where user_id is null', t)
        into empty_count;
      if empty_count = 0 then
        execute format('alter table public.%I alter column user_id set not null', t);
      else
        raise notice '%: user_id boş % kayıt var, NOT NULL eklenmedi', t, empty_count;
      end if;
    end if;
  end loop;
end $$;

-- type yalnızca 'gelir' veya 'gider' olabilir (mevcut kayıtlar kontrol edilmez)
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'categories_type_check') then
    alter table public.categories
      add constraint categories_type_check check (type in ('gelir', 'gider')) not valid;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'transactions_type_check') then
    alter table public.transactions
      add constraint transactions_type_check check (type in ('gelir', 'gider')) not valid;
  end if;
end $$;

-- Kategori silinince işlemler sessizce silinmesin: işlemi olan kategori
-- silinemez (uygulama kullanıcıya kaç işlem olduğunu söyler).
-- category_id üzerindeki CASCADE vb. eski yabancı anahtarlar kaldırılır.
do $$
declare
  c record;
begin
  if not exists (select 1 from pg_constraint
                 where conname = 'transactions_category_id_fkey'
                   and conrelid = 'public.transactions'::regclass
                   and confdeltype = 'a') then
    for c in
      select conname from pg_constraint
      where conrelid = 'public.transactions'::regclass
        and contype = 'f'
        and conkey = array[(select attnum from pg_attribute
                            where attrelid = 'public.transactions'::regclass
                              and attname = 'category_id')]
    loop
      execute format('alter table public.transactions drop constraint %I', c.conname);
    end loop;

    alter table public.transactions
      add constraint transactions_category_id_fkey
      foreign key (category_id) references public.categories (id) not valid;
  end if;
end $$;

-- ─── 3. Satır bazlı güvenlik (RLS) ──────────────────────────────────
-- Anon anahtar uygulamanın içinde herkese açıktır; her kullanıcının
-- yalnızca kendi kayıtlarına erişebilmesini RLS sağlar.

alter table public.categories enable row level security;
alter table public.transactions enable row level security;

-- Adı ne olursa olsun eski politikalar kaldırılır: herkese açık bir
-- politika kalırsa izinler OR ile birleştiği için kısıtlama işe yaramaz.
do $$
declare
  p record;
begin
  for p in
    select policyname, tablename from pg_policies
    where schemaname = 'public' and tablename in ('categories', 'transactions')
  loop
    execute format('drop policy %I on public.%I', p.policyname, p.tablename);
  end loop;
end $$;

create policy "Kendi kategorilerini görür" on public.categories
  for select to authenticated using (user_id = (select auth.uid()));
create policy "Kendine kategori ekler" on public.categories
  for insert to authenticated with check (user_id = (select auth.uid()));
create policy "Kendi kategorisini günceller" on public.categories
  for update to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy "Kendi kategorisini siler" on public.categories
  for delete to authenticated using (user_id = (select auth.uid()));

create policy "Kendi işlemlerini görür" on public.transactions
  for select to authenticated using (user_id = (select auth.uid()));
create policy "Kendine işlem ekler" on public.transactions
  for insert to authenticated with check (user_id = (select auth.uid()));
create policy "Kendi işlemini günceller" on public.transactions
  for update to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy "Kendi işlemini siler" on public.transactions
  for delete to authenticated using (user_id = (select auth.uid()));

-- Eski sürümlerden kalan 'receipts' tablosu uygulamada kullanılmıyor.
-- Erişime kapatılır; içindeki veriye ihtiyacınız yoksa silebilirsiniz:
--   drop table if exists public.receipts;
alter table if exists public.receipts enable row level security;

-- ─── 4. İndeksler ───────────────────────────────────────────────────

create index if not exists categories_user_id_idx
  on public.categories (user_id);
create index if not exists transactions_user_id_date_idx
  on public.transactions (user_id, date desc);
create index if not exists transactions_category_id_idx
  on public.transactions (category_id);

commit;

-- ─── 5. Kontrol ─────────────────────────────────────────────────────
-- Beklenen: categories ve transactions için rls_acik = true, politika_sayisi = 4
select c.relname as tablo,
       c.relrowsecurity as rls_acik,
       (select count(*) from pg_policies p
        where p.schemaname = 'public' and p.tablename = c.relname) as politika_sayisi
from pg_class c
join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public'
  and c.relname in ('categories', 'transactions', 'receipts')
order by c.relname;
